const MACRON = { a: 'ā', i: 'ī', u: 'ū', e: 'ē', o: 'ō' };

// 把單字拆成一個一個假名（拗音算一個），一律換成平假名；っ 和 ー 各自一格
function split(word) {
  const h = toHiragana(word);
  const out = [];
  for (let i = 0; i < h.length; i++) {
    if (BY_KANA[h.slice(i, i + 2)]) out.push(h.slice(i++, i + 1));
    else out.push(h[i]);
  }
  return out;
}

// っ 重複下一個子音（きって → kitte），ー 把前一個母音拉長（ケーキ → kēki）
function toRomaji(units) {
  let r = '';
  let double = false;
  for (const u of units) {
    if (u === 'っ') double = true;
    else if (u === 'ー') r = r.replace(/[aiueo]$/, (v) => MACRON[v]);
    else {
      const s = BY_KANA[u].romaji;
      r += double ? (s.startsWith('ch') ? 't' : s[0]) + s : s;
      double = false;
    }
  }
  return r;
}

const parse = (text, script) =>
  text
    .trim()
    .split(/[|\n]/)
    .map((entry) => {
      const [kana, zh] = entry.trim().split(' ');
      const units = split(kana);
      // kinds：用到的假名（不含 っ、ー），用來判斷這個單字在不在練習範圍裡
      return { kana, zh, script, romaji: toRomaji(units), kinds: units.filter((u) => BY_KANA[u]), size: units.length };
    });

export const WORDS = [...parse(HIRA, 'hira'), ...parse(KATA, 'kata')];
