const pair = (body) => {
  const [ja = '', zh = ''] = body.split('|').map((s) => s.trim());
  return { ja, zh, romaji: ja ? romajiOf(ja) : '' };
};

function parse(text) {
  const scenes = [];
  let scene = null;
  let q = null;
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    const tag = line[0];
    const body = line.slice(1).trim();
    if (tag === '@') {
      const [head, sample = ''] = body.split('|').map((s) => s.trim());
      const [id, name] = head.split(' ');
      scene = { id, name, sample, items: [] };
      scenes.push(scene);
    } else if (tag === '?') {
      q = { kind: 'scene', scene: scene.id, ask: body, they: null, answer: null, wrong: [], note: '' };
      scene.items.push(q);
    } else if (tag === '>') q.they = pair(body);
    else if (tag === '=') q.answer = pair(body);
    else if (tag === '-') q.wrong.push(pair(body));
    else if (tag === '!') q.note = body;
  }
  // 練習紀錄的編號：情境＋正確答案（答案改了，紀錄就重新算）
  for (const s of scenes) for (const q of s.items) q.id = `${s.id}:${q.answer.ja || q.answer.zh}`;
  return scenes;
}

export const SCENES = parse(TEXT);
export const SCENE_BY_ID = Object.fromEntries(SCENES.map((s) => [s.id, s]));
export const SCENE_ITEMS = SCENES.flatMap((s) => s.items);
export const sceneKey = (q) => `scene:${q.id}`;

// 開發時檢查：每題都要有答案、三個錯的選項，編號不能重複
if (import.meta.env?.DEV) {
  const seen = new Set();
  for (const q of SCENE_ITEMS) {
    if (!q.answer || q.wrong.length !== 3) console.warn(`情境題少了選項：${q.ask}`);
    if (seen.has(q.id)) console.warn(`情境題編號重複：${q.id}`);
    seen.add(q.id);
  }
}
